export function libraryCollectionItems(): BgmCollectionItem[] {
  return LIBRARY.map((entry) =>
    makeCollectionItem({
      subject_id: entry.id,
      type: entry.type,
      rate: entry.rate,
      ep_status: entry.epStatus,
      comment: entry.comment,
      updated_at: entry.updatedAt,
      tags: [],
      subject: {
        id: entry.id,
        type: 2,
        name: entry.name,
        name_cn: entry.nameCn,
        short_summary: `${entry.nameCn} 的简短简介`,
        date: entry.year,
        images: {
          large: `https://lain.bgm.tv/pic/cover/l/${entry.id}.jpg`,
          common: `https://lain.bgm.tv/pic/cover/c/${entry.id}.jpg`,
          medium: '',
          small: '',
          grid: '',
        },
        volumes: 0,
        eps: entry.eps,
        collection_total: 1000 + entry.id,
        score: entry.score,
        rank: entry.id * 10,
        tags: entry.tags.map((tag, index) => ({
          name: tag,
          count: 100 - index * 10 - entry.id,
          total_count: 5000,
        })),
      },
    }),
  );
}

export function librarySubjects(): Record<number, BgmSubject> {
  return Object.fromEntries(
    LIBRARY.map((entry) => [
      entry.id,
      makeSubject({
        id: entry.id,
        name: entry.name,
        name_cn: entry.nameCn,
        date: entry.year,
        platform: entry.platform,
        eps: entry.eps,
        total_episodes: entry.eps,
        summary: `${entry.nameCn} 的完整简介`,
        rating: {
          rank: entry.id * 10,
          total: 5000 - entry.id * 10,
          score: entry.score,
          count: {
            '1': 1,
            '2': 2,
            '3': 5,
            '4': 10,
            '5': 50,
            '6': 200,
            '7': 500,
            '8': 400,
            '9': 150,
            '10': 50,
          },
        },
        collection: { wish: 50, collect: 300, doing: 20, on_hold: 10, dropped: 5 },
        infobox: [
          { key: '中文名', value: entry.nameCn },
          { key: '别名', value: [{ v: `${entry.name} English Alias` }] },
          { key: '动画制作', value: entry.studio },
          { key: '导演', value: entry.director },
          { key: '原作', value: entry.id % 2 === 0 ? '漫画改' : '原创' },
        ],
        tags: entry.tags.map((tag, index) => ({
          name: tag,
          count: 100 - index * 10 - entry.id,
          total_count: 5000,
        })),
      }),
    ]),
  );
}
